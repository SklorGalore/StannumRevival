from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "tests/fixtures/raw"


def sections(rev):
    names = ["bus"]
    if rev >= 24:
        names += ["load"]
    if rev >= 31:
        names += ["fixed shunt"]
    names += ["generator", "branch", "transformer adjustment" if rev <= 27 else "transformer", "area", "two-terminal DC"]
    if rev >= 29:
        names += ["voltage source converter"]
    if rev <= 30:
        names += ["switched shunt"]
    names += ["impedance correction", "multi-terminal DC", "multi-section line", "zone", "inter-area transfer"]
    if rev >= 25:
        names += ["owner"]
    if rev >= 26:
        names += ["FACTS control device"]
    if rev >= 31:
        names += ["switched shunt"]
    if rev >= 32:
        names += ["GNE device"]
    if rev >= 33:
        names += ["induction machine"]
    return names


def write(name, rev, data):
    text = f"0,100,{rev},0,0,60\nrs-power synthetic reference: {name}\nGenerated by scripts/generate_raw_inputs.py\n"
    for section in sections(rev):
        text += data.get(section, "") + f"0 / END OF {section.upper()} DATA\n"
    (ROOT / f"{name}.raw").write_text(text + "Q\n")


